// Writes game/ASSETS.md (the asset inventory and licence record) and the
// generated part of game/CREDITS.md from the runtime catalog. Run after build.mjs:
//   node game/scripts/assets/inventory.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const game = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const { assets } = JSON.parse(readFileSync(join(game, "src/assets/catalog.json"), "utf8"));
const list = Object.values(assets);
const kb = (b) => (b / 1024).toFixed(0) + " KB";
const mb = (b) => (b / 1024 / 1024).toFixed(1) + " MB";
const total = list.reduce((s, a) => s + a.lods.reduce((t, l) => t + l.bytes, 0), 0);
const byCat = {};
for (const a of list) (byCat[a.category] ??= []).push(a);

let md = `# Asset inventory\n\n`;
md += `Generated by \`game/scripts/assets/inventory.mjs\` from \`game/src/assets/catalog.json\`. Do not edit it by hand.\n\n`;
md += `${list.length} assets, ${mb(total)} on disk (every LOD, compressed). All files are served from \`public/models\`; nothing is fetched from a third party while playing.\n\n`;
md += `| Category | Assets | Size |\n|---|---|---|\n`;
for (const [c, as] of Object.entries(byCat)) md += `| ${c} | ${as.length} | ${mb(as.reduce((s, a) => s + a.lods.reduce((t, l) => t + l.bytes, 0), 0))} |\n`;
md += `\n## Licences\n\n`;
const lic = {};
for (const a of list) (lic[a.license] ??= []).push(a.id);
for (const [l, ids] of Object.entries(lic)) md += `- **${l}**: ${ids.length} asset${ids.length > 1 ? "s" : ""}\n`;
md += `\nCC BY assets are credited in the game (Credits, on the title screen) and in \`CREDITS.md\`.\n`;
for (const [c, as] of Object.entries(byCat)) {
  md += `\n## ${c[0].toUpperCase() + c.slice(1)}\n\n| ID | Name | Creator | Licence | Size (m, L×H×W) | LODs (triangles, file size, switch distance) | Collision | Animations |\n|---|---|---|---|---|---|---|---|\n`;
  for (const a of as.sort((x, y) => x.id.localeCompare(y.id))) {
    const dims = a.dimensions ? a.dimensions.map((d) => d.toFixed(2)).join(" × ") : "-";
    const lods = a.lods.map((l, i) => `${i}: ${l.triangles.toLocaleString("en")} tris, ${kb(l.bytes)}${l.distance ? `, from ${l.distance} m` : ""}`).join("<br>");
    const anim = a.animations ? `${a.animations.length} clips` : a.kind === "skinned" ? "shared library" : "-";
    md += `| \`${a.id}\` | [${a.name}](${a.source}) | ${a.creatorUrl ? `[${a.creator}](${a.creatorUrl})` : a.creator} | ${a.license} | ${dims} | ${lods} | ${a.collision.shape}${a.collision.note ? ` (${a.collision.note})` : ""} | ${anim} |\n`;
  }
}
writeFileSync(join(game, "ASSETS.md"), md);

// CREDITS.md: replace the generated block.
const creditsFile = join(game, "CREDITS.md");
const credits = readFileSync(creditsFile, "utf8");
const start = "<!-- assets:start -->", end = "<!-- assets:end -->";
let block = `${start}\n## 3D models\n\n| Model | Creator | Licence | Source |\n| --- | --- | --- | --- |\n`;
const groups = new Map();
for (const a of list) {
  const key = a.creator + "|" + a.license + "|" + (a.category === "people" ? "people" : a.id);
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(a);
}
for (const as of groups.values()) {
  const a = as[0];
  const name = as.length > 1 ? `${as.length} ${a.category} (${as.slice(0, 3).map((x) => x.name.replace(/ \(.*\)$/, "")).join(", ")}${as.length > 3 ? ", …" : ""})` : a.name;
  block += `| ${name} | ${a.creatorUrl ? `[${a.creator}](${a.creatorUrl})` : a.creator} | ${a.license} | ${a.source} |\n`;
}
block += `\nThe people are generated with [Ara 3D Gen](https://github.com/olatunde85/3d-gen) (MIT) from MakeHuman's CC0 assets; their animations are from the [CMU Graphics Lab Motion Capture Database](http://mocap.cs.cmu.edu) (free to use, not to be resold on its own; created with funding from NSF EIA-0196217).\n${end}`;
const out = credits.includes(start) ? credits.replace(new RegExp(`${start}[\\s\\S]*${end}`), block) : credits.replace("## Libraries", block + "\n\n## Libraries");
writeFileSync(creditsFile, out);
console.log(`ASSETS.md: ${list.length} assets, ${mb(total)}; CREDITS.md updated`);
